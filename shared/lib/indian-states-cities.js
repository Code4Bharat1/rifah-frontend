// City to State lookup
export const CITY_TO_STATE_MAP = (() => {
  const map = new Map();
  Object.entries(INDIAN_STATES_AND_CITIES).forEach(([state, cities]) => {
    cities.forEach(({ city }) => {
      map.set(city.trim().toLowerCase(), state);
      if (city.includes("(") && city.includes(")")) {
        const primary = city.split("(")[0].trim().toLowerCase();
        const inside = city.match(/\((.*?)\)/)?.[1]?.trim().toLowerCase();
        if (primary && !map.has(primary)) map.set(primary, state);
        if (inside && !map.has(inside)) map.set(inside, state);
      }
    });
  });
  return map;
})();

/**
 * Returns a sorted list of city names for the given state.
 * If no state is provided, returns all unique cities across India.
 */
export function getCitiesForState(stateName) {
  if (!stateName || typeof stateName !== "string") {
    // Return all cities
    const all = [];
    Object.values(INDIAN_STATES_AND_CITIES).forEach((list) => {
      list.forEach((item) => all.push(item.city));
    });
    return Array.from(new Set(all)).sort((a, b) => a.localeCompare(b));
  }

  const normalized = stateName.trim().toLowerCase();
  for (const [state, list] of Object.entries(INDIAN_STATES_AND_CITIES)) {
    if (state.toLowerCase() === normalized) {
      return list.map((item) => item.city).sort((a, b) => a.localeCompare(b));
    }
  }

  return [];
}

/**
 * Finds the default headquarters/central pincode for a given city name.
 */
export function getPincodeForCity(cityName) {
  if (!cityName || typeof cityName !== "string") return "";
  const key = cityName.trim().toLowerCase();
  return CITY_TO_PINCODE_MAP.get(key) || "";
}

/**
 * Finds the corresponding state for a given city name.
 */
export function getStateForCity(cityName) {
  if (!cityName || typeof cityName !== "string") return "";
  const key = cityName.trim().toLowerCase();
  return CITY_TO_STATE_MAP.get(key) || "";
}
