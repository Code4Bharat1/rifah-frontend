export const DEFAULT_COUNTRY = COUNTRIES[0]; // India (+91)

/**
 * Parses any incoming phone string into country object and national number.
 * e.g. "+91 9876543210" -> { country: IN, nationalNumber: "9876543210" }
 *      "+971501234567"  -> { country: AE, nationalNumber: "501234567" }
 *      "9876543210"     -> { country: IN, nationalNumber: "9876543210" }
 */
export function parsePhoneNumber(rawPhone, defaultCountryCode = "IN") {
  const defaultCountry = COUNTRIES.find((c) => c.code === defaultCountryCode) || DEFAULT_COUNTRY;
  if (!rawPhone || typeof rawPhone !== "string") {
    return { country: defaultCountry, nationalNumber: "" };
  }

  const trimmed = rawPhone.trim();
  if (!trimmed) {
    return { country: defaultCountry, nationalNumber: "" };
  }

  if (trimmed.startsWith("+")) {
    // Sort dial codes descending by length so longer codes match first (e.g. +880 before +88)
    const sorted = [...COUNTRIES].sort((a, b) => b.dialCode.length - a.dialCode.length);
    const cleanNoPlus = trimmed.slice(1);
    for (const c of sorted) {
      const codeDigits = c.dialCode.replace("+", "");
      if (cleanNoPlus.startsWith(codeDigits)) {
        const national = cleanNoPlus.slice(codeDigits.length).trim();
        return { country: c, nationalNumber: national };
      }
    }
  }

  // If phone starts with "00", e.g. 00971...
  if (trimmed.startsWith("00")) {
    const without00 = "+" + trimmed.slice(2);
    return parsePhoneNumber(without00, defaultCountryCode);
  }

  // Otherwise assume national number for default country
  return { country: defaultCountry, nationalNumber: trimmed };
}

/**
 * Combines country dial code and national number.
 * Returns empty string if national number is blank (prevents saving bare "+91").
 */
export function formatPhoneNumber(country, nationalNumber) {
  const digits = (nationalNumber || "").replace(/[^\d]/g, "").trim();
  if (!digits) return "";
  const dial = country?.dialCode || "+91";
  return `${dial} ${digits}`;
}
